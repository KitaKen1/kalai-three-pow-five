"""Paper specification of the signed-face recurrence closing two full pairs."""
import json
from verification.paths import ROOT

def add_signed_carriers(p,eq,section,table,width):
    from .paper_endpoints import tuple_text
    section(49,'Signed face cuts close the two-full-pair endpoint')
    p('Let F,−F,H,−H be the four full facets. '
      'Their normalized supporting functions take '
      'values ±1 on every vertex of P. '
      'Choose signs so that F and H agree '
      'on k≥4 of the eight antipodal vertex '
      'pairs. Distinct pairs give k≤7. '
      'Their actual common vertex set has '
      'k vertices; F∩(−H) has 8−k.')
    p('<b>The seven-common-vertex case.</b> If k=7, '
      'the seven common vertices lie in '
      'the intersection of two distinct '
      'support hyperplanes, of affine '
      'dimension three. Their linear '
      'span L has dimension at most '
      'four. All vertices of P are '
      'these seven points, their negatives '
      'and one remaining antipodal pair '
      '±a. Full dimension forces dim L=4 '
      'and a∉L. Thus P is the free '
      'sum of the centrally symmetric '
      'four-polytope Q=conv(±B) in L '
      'and the segment [−a,a]. Polarity '
      'turns this into a product; the '
      'nonempty-face count is 3s(Q). '
      'Section 27 gives s(Q)≥81, '
      'so s(P)≥243. Hence k=7 '
      'cannot be a counterexample.')
    p('It remains to test k=4,5,6. For each '
      'seven-vertex nonfull facet X, label '
      'its abstract vertices 0,…,6 and '
      'let M be their set. Let S be '
      'the vertices of X in F and '
      'U those in H. Fullness gives '
      'the complementary cuts M∖S and '
      'M∖U for −F and −H. All four '
      'are faces of X, with the empty '
      'face allowed and X itself excluded. '
      'They can be read from the '
      'exact seven-vertex Gale lattices. '
      'Every label has one of the '
      'four sign combinations. Thus')
    eq('|S∩U|+|(M∖S)∩(M∖U)|≤k,<br/>'
       '|S∩(M∖U)|+|(M∖S)∩U|≤8−k.','49.1')
    p('These inequalities simply say that the '
      'seven vertices occupy distinct '
      'antipodal pairs; the one omitted '
      'pair can be in either sign class. '
      'An embedding of X in an actual '
      'P must satisfy them. Conversely '
      'we use them only as necessary '
      'conditions; any unrealizable cut '
      'retained by this test enlarges '
      'the search and cannot create '
      'a false exclusion.')
    p('For every allowed cut record the ridge '
      'type j<sub>F</sub> when either '
      'S or M∖S has dimension three, '
      'or zero when neither does. Both '
      'cannot have dimension three, since '
      'two disjoint ridges need at least '
      'eight vertices. Define j<sub>H</sub> '
      'similarly. The type indices are '
      '1,…,12 in Section 36. Record '
      'the exact weight w of X and '
      'the parity mask π=Σ2<super>j−1</super> '
      '(cⱼ mod 2).')
    p('Also record eight numbers z. For the '
      'positive full intersection F∩H, '
      'count the two-faces S∩U and '
      '(M∖S)∩(M∖U) that are in a '
      'three-dimensional cut belonging '
      'to F; record their count and '
      'total vertex count. Do the '
      'same for three-dimensional cuts '
      'belonging to H. These give '
      'the first four entries of z. '
      'For the negative intersection '
      'F∩(−H), replace U by M∖U '
      'and obtain the last four. '
      'Every dimension and vertex count '
      'here is determined by the '
      'small facet face lattice. Retain '
      'each distinct tuple (j<sub>F</sub>, '
      'j<sub>H</sub>,w,π;z) once.')
    p('For transparency the complete cut-tuple '
      'inputs needed for the nine residual '
      'lists are printed below. They '
      'are generated by visiting all '
      'face masks S,U whose complements '
      'are proper faces, testing (49.1), '
      'and applying the preceding definitions. '
      'Facet row IDs are from Section 46. '
      'The symbol 0 denotes no ridge '
      'neighbour; π is written as an '
      'ordinary integer bit mask. The '
      'eight z entries are in the '
      'displayed order, including unused '
      'negative-intersection entries.')
    D=json.loads((ROOT/'evidence/signed-carrier-checks.json').read_text())
    ids={(7,15,14,6,29):1,(7,16,16,7,32):2,(7,17,18,8,35):4,(7,17,18,8,36):5}
    for x in sorted(D['carrier_patterns'],key=lambda x:(tuple(x['row']),x['k'])):
        R=tuple(x['row'])
        if R not in ids or x['k']==7:continue
        def show(a):
            jf,jh,w,pi,z=a
            return tuple_text((0 if jf is None else jf+1,0 if jh is None else jh+1,w,pi))+':'+tuple_text(z)
        p('<b>ID '+str(ids[R])+', k='+str(x['k'])+'.</b> '+
          '; '.join(show(a) for a in x['patterns'])+'.')
    p('<b>The exact recurrence.</b> Choose local options '
      '(c<sub>F</sub>,q<sub>F</sub>,b<sub>F</sub>,w<sub>F</sub>) '
      'and the corresponding H option from Section 48. '
      'The possible shared full ridges are: none; '
      'one ridge of a type with k vertices present '
      'in both options; and, only when k=4, '
      'two tetrahedra. The last case uses both '
      'F∩H and F∩(−H). For k≥5, '
      'no shared ridge would make F∩H '
      'a k-gon. Therefore it requires '
      'η(F)−q(F)≥k−3 and η(H)−q(H)≥k−3. '
      'Discard the no-ridge choice unless '
      'both inequalities hold.')
    p('Subtract each shared ridge from c<sub>F</sub> '
      'and c<sub>H</sub> to obtain target '
      'vectors a,d for the seven nonfull '
      'pairs. A shared ridge of type '
      '(n,e,r) has r polygons and total '
      'polygon vertex count 2e. Set '
      'its corresponding four z targets '
      'to (r,2e,r,2e). With one shared '
      'ridge use the positive-intersection '
      'entries; with two use both blocks. '
      'Unused blocks are ignored. Set '
      'the weight allowance to '
      'L=78−3S−w<sub>F</sub>−w<sub>H</sub> '
      'and the final parity target to '
      'the exclusive-or of their masks.')
    p('Start with the state (a,d,z,π=0,L). '
      'Visit the seven nonfull row IDs '
      'in their printed order. For each '
      'tuple from that row’s cut table, '
      'subtract one from a at j<sub>F</sub> '
      'when nonzero, one from d at '
      'j<sub>H</sub> when nonzero, subtract '
      'its used z entries and its '
      'weight, and replace π by its '
      'exclusive-or with the tuple’s mask. '
      'Discard any state with a negative '
      'integer entry. At the end accept '
      'exactly zero target vectors and '
      'the required parity, with a '
      'nonnegative remaining weight allowance. '
      'Equal states may be combined; '
      'this is only a way of avoiding '
      'repeated additions and subtractions.')
    p('Why must a real polytope give an accepted '
      'state? Every ridge of F and H '
      'has its unique second facet, so '
      'the two ridge-count targets are '
      'exhausted exactly. Every polygon '
      'of a shared ridge T has, inside '
      'F, a unique other ridge R. '
      'Its second facet X is nonfull '
      'and R∩T=T∩X is that polygon. '
      'Thus the F-side polygon targets '
      'are exhausted exactly; the same '
      'holds on the H side. The '
      'weight and type-parity targets '
      'were proved in Sections 45,48. '
      'All possible sign cuts of each '
      'X have been retained. Hence '
      'rejecting every state excludes '
      'every actual realization.')
    p('For each of the nine residual lists '
      'the recurrence gives the following '
      'complete output. The supplied '
      'integer program recomputes the '
      'Gale cuts, table entries and '
      'state counts from these definitions; '
      'all calculations are exact.')
    table([['<b>(G,S)</b>','<b>Nine row IDs</b>','<b>Accepted states</b>']]+
          [[tuple_text((x['G'],x['S'])),tuple_text(s['ids']),str(s['witness_count'])]
           for x in D['cells'] for s in x['profiles']],
          [50,width-140,90],compact=True)
    p('Every count is zero. Section 47 excluded '
      'the four other positive cells, '
      'and Section 44 excluded the '
      'zero-stress cell. Therefore the '
      '(16,18) endpoint with two full '
      'facet pairs is completely excluded. □')
