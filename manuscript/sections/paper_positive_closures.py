"""Geometric proofs eliminating four of the eight positive cells."""
def add_positive_closures(p,eq,section,table,width):
    section(47,'Prisms, tetrahedral parity, and four positive-cell exclusions')
    p('<b>Lemma 47.1.</b> <i>If a four-polytope has at most '
      'eight vertices and a triangular-prismatic ridge, '
      'then b=0.</i> Suppose instead that a quadrilateral '
      'Q is shared by square-pyramidal ridges R,S. Let '
      'T be a prismatic ridge. Q is not in T, because '
      'its two ridge neighbours are already R,S. '
      'Each of T∩R,T∩S has at least 6+5−8=3 '
      'vertices. These intersections are polygonal '
      'faces of square pyramids different from Q, '
      'hence triangles. They are different: otherwise '
      'three ridges would meet in a two-face. '
      'A triangular prism has just two triangular '
      'faces, its disjoint bases. Thus T∩R∩S=T∩Q '
      'has no vertices. But T and Q would then '
      'use ten distinct vertices. This contradiction '
      'proves the lemma. □')
    p('<b>Lemma 47.2.</b> <i>For V=(8,19,19,8;39), '
      'the actual weight is twelve.</i> Count ridge '
      'vertices minus ridge polygons: Σ(n(T)−f₂(T)) '
      '=39−2·19=1. Among the twelve possible '
      'ridge triples, only (6,9,5) and (7,11,6) '
      'have positive difference, namely one. '
      'The second is impossible. Indeed, an '
      'eight-vertex facet with a seven-vertex '
      'ridge is a pyramid, and has one more '
      'ridge than that base has polygons: here '
      'at most seven instead of eight. '
      'Therefore V has a prism. Lemma 47.1 '
      'gives b=0. Since η=4, its three '
      'quadrilaterals and η−q≠1 force q=4 '
      'and no larger polygons. Thus w=4+8=12. □')
    p('<b>Lemma 47.3.</b> <i>An eight-vertex four-polytope '
      'with three tetrahedral ridges and all other '
      'ridges square pyramids has at least 22 '
      'edges.</i> At a vertex x, let a(x) be '
      'the number of tetrahedra containing x '
      'and q(x) the number of quadrilaterals '
      'containing x. A tetrahedron contributes '
      'degree three at x. A square pyramid '
      'contributes four at its apex, three '
      'at a base vertex. If k(x) is the '
      'number of ridges through x, summing '
      'these degrees gives 4k(x)−a(x)−2q(x). '
      'It is even: it is the sum of the '
      'polygon lengths of the three-dimensional '
      'vertex figure, twice its edge count. '
      'Consequently a(x) is even.')
    p('There are three tetrahedra A,B,C, so each '
      'vertex belongs to zero or two. In '
      'particular the triple intersection is '
      'empty. Put α=|A∩B|, β=|A∩C|, '
      'γ=|B∩C|. Their four-vertex sets '
      'give α+β=α+γ=β+γ=4. Thus '
      'α=β=γ=2, and their union has '
      'six vertices. Its tetrahedral edges '
      'number at least 3·6−3=15, because '
      'each pair can share at most the '
      'one edge on its two common vertices. '
      'The other two vertices have degree '
      'at least four each, as every vertex '
      'of a four-polytope does. Their edge '
      'stars are outside the six-vertex '
      'core and overlap in at most their '
      'mutual edge. They add at least seven '
      'edges, giving 22. □')
    p('Use IDs from Section 46, and put '
      'D=(7,17,18,8;36), R₀=(8,18,17,7;36), '
      'R₃₅=(8,18,17,7;35), '
      'C₂₀=(8,20,20,8;39), '
      'Q₉=(8,20,21,9;42). '
      'These letters label facet rows only. '
      'The planar Gale recurrence, applied '
      'also to dual rows, gives: D has '
      'four tetrahedra and four square '
      'pyramids; every ridge of R₀ is '
      'a tetrahedron, square pyramid or '
      'triangular prism; R₃₅ necessarily '
      'has a (6,10,6) or (7,11,6) ridge. '
      'These tests involve seven-vertex '
      'diagrams and are included in the '
      'independent catalogue calculation.')
    p('<b>The (4,4) cell.</b> Its only pair list '
      'is Y⁶,D,V,C₂₀. The pair weight is '
      'at least 54+12+3=69, exceeding '
      '78−3·4=66. Thus it is impossible.')
    p('<b>The (4,2) cell.</b> The four lists are '
      'Y⁵,D²,R₃₅,R₀; Y⁵,E,D,R₀,V; '
      'Y⁶,D,R₀,Q₉; Y⁶,D,V². '
      'The second and fourth have pair '
      'weights at least 45+4+15+12=76 '
      'and 54+24=78 respectively, exceeding '
      'the budget 72. In the first list '
      'only the one R₃₅ pair could supply '
      'its special ridge type. Every ridge '
      'has a distinct second facet, which '
      'cannot be the antipode of the first: '
      'a proper face contains no antipodal '
      'vertices. Thus a ridge type absent '
      'from every other row cannot occur '
      'in a row represented by just one '
      'antipodal pair. This excludes the first list.')
    p('Apply that same transfer principle to Q₉ '
      'in the third list. Its ridges must '
      'be tetrahedra, square pyramids or '
      'prisms, since these are the only '
      'types supplied by Y,D,R₀. The '
      'difference Σ(n(T)−f₂(T))=42−42=0 '
      'then forces no prisms; the other '
      'two types have difference zero, '
      'prisms difference one. The count '
      'equations Σc=9, Σnc=42 give '
      'three tetrahedra and six square '
      'pyramids. Lemma 47.3 would require '
      '22 edges, whereas Q₉ has 20. '
      'This excludes the third list and the cell.')
    p('<b>The (2,10) cell.</b> The only pair list '
      'is Y⁵,J²,H₂₀,C₂₀, where '
      'H₂₀=(8,20,20,8;38). Its lower '
      'weight is 45+3=48, exactly the '
      'budget 78−30. Thus C₂₀ attains '
      'weight three. A prism in C₂₀ '
      'would give b=0 by Lemma 47.1 '
      'and q≥3, hence w≥9 since η=3. '
      'There is no prism in C₂₀. There '
      'is none in H₂₀ either: η=2 '
      'cannot contain three quadrilaterals. '
      'The J profile has no prism, '
      'whereas Y has one. Consequently '
      'the actual ten Y facets account '
      'for exactly ten prism incidences. '
      'Every ridge belongs to two facets '
      'and every ridge has a distinct '
      'antipode, so such a count is '
      'divisible by four. Ten is not. '
      'The cell is excluded.')
    p('<b>The (4,6) cell.</b> The only pair list '
      'is Y⁶,D,C₂₀², and its pair weight '
      '54+6=60 equals the budget. Each '
      'C₂₀ attains weight three. The '
      'twelve ridge-count equations and '
      'reserved quadrilateral inequalities '
      'of Section 41 now give q=3,b=2, '
      'no larger polygon, and exactly '
      'two tetrahedra, five square pyramids '
      'and one (6,11,7) ridge. This is '
      'the unique minimizing count vector '
      'for C₂₀ in the printed Section 41 calculation.')
    p('Write F,H for full C₂₀ facets sharing '
      'the (6,11,7) ridge T. Its second '
      'facet must be full, because Y,D '
      'lack that ridge type. Full facets '
      'choose exactly one vertex from '
      'each of the eight antipodal pairs. '
      'They agree on the six vertices '
      'of T and disagree on the remaining '
      'two: write F∖T={a,b}, '
      'H∖T={−a,−b}. The four full '
      'facets are F,H,−F,−H. '
      'Only H can be a full ridge '
      'neighbour of F: −F is disjoint '
      'and F∩(−H) has only two vertices.')
    p('Each full facet has eight ridges, so '
      'each has seven nonfull neighbours. '
      'A nonfull facet cannot neighbour '
      'both members of an antipodal full '
      'pair: the disjoint intersections '
      'would be two ridges of at least '
      'four vertices each, exceeding its '
      'seven vertices. It has at most '
      'two full neighbours. The four '
      'full facets give 28 full/nonfull '
      'adjacencies and the fourteen '
      'nonfull facets can give at most '
      '28. Therefore each nonfull '
      'facet has exactly two full neighbours.')
    p('In F choose a square-pyramidal ridge R '
      'whose intersection with T is a '
      'triangle. Such a choice exists: '
      '5+6−8=3 forces a polygonal '
      'intersection for each of the '
      'five square pyramids, whereas T '
      'has only one quadrilateral and '
      'that face has only one partner '
      'other than T. Thus R contains '
      'a,b and three vertices of T. '
      'Its second facet X is nonfull.')
    p('X cannot neighbour −F, since its ridge '
      'in −F would be disjoint from '
      'the five vertices of R. It '
      'cannot neighbour H: it contains '
      'a,b and hence not −a,−b; '
      'a ridge in H would be contained '
      'in T and therefore equal T, '
      'forcing eight vertices in X. '
      'Finally, T has seven polygons '
      'and H has exactly seven other '
      'ridges. The other ridge over '
      'each polygon of T is distinct, '
      'so every ridge of H except T '
      'meets T in a polygon. Every '
      'ridge U of −H except −T '
      'therefore has at least three '
      'vertices in −T. These are '
      'disjoint from R⊆F, so X '
      'cannot contain U. Nor can '
      'X contain −T itself. Hence '
      'X has F as its only full '
      'neighbour, contradicting the '
      'equality count above. This excludes '
      'the (4,6) cell. □')
    p('Of the eight positive two-pair cells, '
      'only (2,2),(2,4),(2,6),(2,8) '
      'remain for the further geometric '
      'argument. The arithmetic lists '
      'for these cells are retained in '
      'Section 46; no existence claim '
      'is made about any surviving list.')
