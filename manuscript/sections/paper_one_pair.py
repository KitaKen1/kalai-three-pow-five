"""Ordinary incidence proof of the one-full-pair (16,18) residue."""
def add_one_pair(p,eq,section,table,width):
    section(43,'The one-full-pair residue: four tetrahedra instead of two')
    p('<b>Proposition 43.1.</b> <i>The (16,18) endpoint '
      'with one full facet pair is excluded.</i> '
      'By Section 42 a counterexample has G=0,S=10. '
      'All local g vanish by stress localization. '
      'The local stress sum of Section 12, '
      'Σ<sub>pairs</sub>g=G+64−I/2, '
      'therefore gives I=128. The one '
      'full pair contributes sixteen '
      'vertex–facet incidences and the '
      'other sixteen facets have at '
      'most seven vertices. Equality '
      '128=16+16·7 forces all of '
      'them to have seven vertices.')
    p('<b>The full row.</b> At G=0 every '
      'quadrilateral has exactly three '
      'facets in its upper link, by Section '
      '13. In a full eight-vertex facet, '
      'two ridges of at least six '
      'vertices through a quadrilateral '
      'cover its eight vertices. Section '
      '36 proves their link has at '
      'least four facets; thus this '
      'cannot occur. Each quadrilateral '
      'of a triangular-prism ridge '
      'must consequently have a '
      'different square-pyramidal '
      'ridge as partner: any partner '
      'with at least six vertices '
      'would give that full cover. '
      'This requires at least three '
      'square pyramids.')
    p('The complete small dual catalogue '
      'shows that the only eight-vertex '
      'zero-g rows with fewer than '
      'eight ridges are the prism, '
      '(8,18,17,7;35) and '
      '(8,19,18,7;35). The prism '
      'has already been excluded. '
      'In the middle row the catalogue '
      'gives either a prism with '
      'fewer than three square pyramids '
      'or a seven-vertex ridge and '
      'a square pyramid. The latter '
      'facet is a pyramid over that '
      'seven-vertex ridge; the square '
      'pyramid’s quadrilateral lies '
      'in the base. Their seven plus '
      'five vertices minus the shared '
      'four again cover the full facet. '
      'In the last row the catalogue '
      'gives a quadrilateral whose '
      'two containing ridges cover '
      'all eight vertices directly. '
      'These are forbidden full covers. '
      'All statements are obtained by '
      'the signed-order face criterion '
      'of Section 14, on the dual '
      'seven-vertex rows; the independent '
      'catalogue check includes every '
      'such code and the indicated '
      'cover or ridge-count witnesses.')
    p('The full-ridge bound R₈≤16 forces '
      'each of the two full facets to '
      'have exactly eight ridges. Local '
      'g=0 gives J=38. Euler gives '
      'p=e; J+4n≤4e and η≥0 '
      'give 18≤e≤22. Section 36 '
      'excludes the e=18 fake row. '
      'The full row is therefore '
      'H<sub>k</sub>=(8,k,k,8;38), '
      '19≤k≤22.')
    p('<b>The numerical profile.</b> The nine '
      'zero-g seven-vertex rows are '
      'Y=(7,15,14,6;29), E=(7,16,16,7;32), '
      'J=(7,17,17,7;32), followed by '
      '(7,17,18,8;35), (7,17,19,9;38), '
      '(7,18,19,8;35), (7,18,20,9;38), '
      '(7,18,21,10;41), (7,18,22,11;44). '
      'Write their pair counts as '
      'y,q,j,a,b,c,d,u,v. They sum '
      'to eight. The flag identities '
      'at G=0,S=10,I=128 give '
      'f₁₄=3e+122. Summing their '
      'edges, ridges and Section 41 '
      'weights yields')
    eq('3e+122=2k+30y+32q+34j+34a+34b+36c+36d+36u+36v,<br/>'
       'r=8+6y+7q+7j+8a+9b+8c+9d+10u+11v,<br/>'
       '9y+4q+3[k=19]+3e≤210.','43.1')
    p('Together with e+r≤118 and the count '
      'sum, the first two lines give '
      '2k+5q+7j+10a+13b+12c+15d+18u+21v≤68. '
      'The weight line gives '
      '2k+3[k=19]≤20+3q+5j+5a+5b+3c+3d+3u+3v. '
      'Five times the first and seven '
      'times the second combine to')
    eq('24k+7·3[k=19]+4q+15a+30b+39c+54d+69u+84v≤480.','43.2')
    p('For k≥21 this is impossible. For '
      'k=19 its constant is 477, '
      'and for k=20 it is 480. '
      'Each nonzero variable except '
      'j,y contributes at least four, '
      'so q=a=b=c=d=u=v=0. '
      'For k=19 the two preceding '
      'inequalities force j≤4 and '
      'j≥5, impossible. For k=20 '
      'they force j=4,y=4. Equation '
      '(43.1) then gives e=58,r=60. '
      'Thus the actual facet multiset is')
    eq('Y⁸ J⁸ H², &nbsp; H=(8,20,20,8;38).','43.3')
    p('The exponents count actual facets. '
      'The independent nine-count '
      'enumeration visits 51,480 '
      'integer profiles and leaves '
      'exactly (43.3), but the '
      'displayed linear combination '
      'already proves the reduction.')
    p('<b>Local equality data.</b> The global '
      'quadrilateral budget is 72, '
      'equal to the weight 8·9 of '
      'the Y facets. Since each local '
      'weight is at most q−3b+2η, '
      'all facets attain their local '
      'lower bound. In H, η=2 and '
      'q−3b+4=0 imply q=b=2: '
      'use b≤q≤2 and η−q≠1. '
      'Both quadrilaterals of H are '
      'between square-pyramidal ridges, '
      'giving four square pyramids. '
      'The reserved-quadrilateral '
      'rules exclude prisms and every '
      'other non-five-vertex ridge '
      'with positive polygon excess. '
      'The twelve count equations '
      'leave either two tetrahedra, '
      'four square pyramids and two '
      'triangular bipyramids, or '
      'three tetrahedra, four square '
      'pyramids and one octahedron.')
    p('Y has two tetrahedra and J has '
      'three, as checked by the '
      'small catalogue. In (43.3) '
      'the number of global tetrahedral '
      'ridges equals the sum of '
      'local tetrahedron counts over '
      'facet-pair representatives. '
      'It is 4·2+4·3 plus H’s '
      'tetrahedron count and must '
      'be even by symmetry. Hence '
      'H has exactly two tetrahedral '
      'ridges, four square pyramids '
      'and two bipyramids. Each '
      'ridge of H contains at most '
      'one quadrilateral. The small '
      'catalogue also gives J exactly '
      'one quadrilateral and no '
      'six-vertex ridge.')
    p('<b>Two Y facets around each quadrilateral.</b> '
      'Y has three quadrilaterals, '
      'each between its prism base '
      'and one square pyramid; its '
      'local q−3b contribution at '
      'each is one. J and H '
      'contribute minus two at each '
      'of their quadrilaterals. '
      'All upper links are triangles. '
      'The Section 36 local link '
      'inequality gives a nonpositive '
      'sum around each link. Its '
      'global sum is '
      '8·3−8·2−2·4=0. Therefore '
      'each link sum is zero, '
      'forcing exactly two Y facets '
      'and one other facet in '
      'every quadrilateral link.')
    p('Each Y prism base K belongs '
      'to a second Y facet Z: '
      'neither J nor H has a '
      'six-vertex ridge. This partner '
      'is unique, and all three '
      'quadrilaterals of K lie in '
      'Y and Z. Choose one full '
      'facet H and its two '
      'quadrilaterals Q₁,Q₂. Each '
      'Qᵢ is therefore accompanied '
      'by a Y,Z pair sharing a '
      'prism Kᵢ. Its other two '
      'quadrilaterals will be called '
      'mixed quadrilaterals. H '
      'shares at most one '
      'quadrilateral with any '
      'other facet, since their '
      'intersection is contained '
      'in a ridge of H. '
      'Consequently none of the '
      'mixed quadrilaterals is '
      'contained in H. The two '
      'sets of mixed quadrilaterals '
      'are disjoint: a shared '
      'one would force its two '
      'Y facets to be both '
      'pairs, and one of those '
      'Y facets would share '
      'Q₁,Q₂ with H. Thus '
      'there are four distinct '
      'mixed quadrilaterals.')
    p('<b>Each mixed quadrilateral forces a tetrahedron.</b> '
      'Fix Q⊂H, its two Y '
      'facets Y,Z and their '
      'prism K. The intersections '
      'H∩Y and H∩Z are '
      'square pyramids over Q, '
      'because the upper link is '
      'a triangle. Their fifth '
      'vertices are precisely '
      'the apices of Y and Z '
      'outside K. In particular '
      'both apices belong to H. '
      'For a mixed quad R of K, '
      'the third facet J′ is '
      'of type J. It is not H '
      'by the preceding paragraph, '
      'nor −H, since R meets '
      'Q in an edge and therefore '
      'contains H vertices. The '
      'intersections J′∩Y,J′∩Z '
      'are square pyramids over '
      'R; each contains the '
      'corresponding apex.')
    p('Here is the exact signed-vertex '
      'count, to justify the intersection '
      'rather than infer it from a '
      'drawing. U=V(Y)∪V(Z) '
      'has 7+7−6=8 vertices '
      'and contains no antipodal '
      'pair: a potential cross '
      'pair either has a member '
      'in K, contradicting Y '
      'or Z, or consists of '
      'the two apices in H. '
      'It therefore selects one '
      'vertex of each antipodal '
      'pair of P. Exactly two '
      'members of U are outside '
      'H, namely V(K)∖V(Q). '
      'Since two distinct prism '
      'quadrilaterals cover its '
      'six vertices, these two '
      'belong to R and hence '
      'to J′. Also U∩V(J′) '
      'has 5+5−4=6 vertices. '
      'Any H∩J′ vertex outside '
      'U would be the antipode '
      'of a member of U. If '
      'that member belongs to H '
      'it is forbidden by H; '
      'otherwise it is one of '
      'the two members just '
      'shown to belong to J′ '
      'and is forbidden by J′. '
      'Thus H∩J′ has exactly '
      '6−2=4 vertices.')
    p('This intersection cannot be a '
      'polygon: it would be a '
      'second quadrilateral of J′, '
      'different from R, which is '
      'not contained in H. Nor '
      'can a face with four '
      'vertices have dimension at '
      'most one. It is therefore '
      'a tetrahedral ridge of H. '
      'Different mixed quadrilaterals '
      'give different J′ facets, '
      'since a J facet has '
      'only one quadrilateral. '
      'Different neighboring facets '
      'give different ridges of H, '
      'since a ridge belongs '
      'to exactly two facets. '
      'The four mixed quadrilaterals '
      'therefore require four '
      'tetrahedral ridges of H, '
      'contrary to its exactly '
      'two. Proposition 43.1 follows.')
