"""All-real five-point-fibre exclusion in the three-full-pair branch."""
def add_cube_three_singleton(p,eq,section,table,width):
    section(50,'The three-full-pair normal form and its five-point fibre')
    p('Three full facet pairs have three independent '
      'normalized support functions, by the '
      'rank argument of Section 28. Project '
      'P by those functions to a subset '
      'of the three-cube. The six-corner '
      'image was handled in Sections 29,33: '
      'a point fibre splits off a segment, '
      'and otherwise its eight lifted '
      'triangular faces are full facets. '
      'The present branch has exactly '
      'six full facets, so that alternative '
      'is excluded. All eight cube '
      'corners are occupied.')
    p('Choose positive corners c₀=(1,1,1), '
      'c₁=(1,1,−1), c₂=(1,−1,1), '
      'c₃=(1,−1,−1). Their relation '
      'is c₀+c₃=c₁+c₂. After a '
      'linear choice of kernel coordinates, '
      'the polytope has the form')
    eq('P=conv{±(cⱼ,z) : z∈Kⱼ, 0≤j≤3},<br/>'
       'Kⱼ⊂ℝ², nⱼ=|Kⱼ|≥1, Σnⱼ=8.','50.1')
    p('Every Kⱼ is in convex position: '
      'a nonextreme point in its fibre '
      'would be a nonextreme vertex '
      'of P. Hence nⱼ≥3 gives '
      'a genuine planar polygon. The '
      'possible unordered sizes are '
      '(5,1,1,1), (4,2,1,1), '
      '(3,3,1,1), (3,2,2,1), '
      '(2,2,2,2). An extra full '
      'support with a nonzero kernel '
      'part would increase the full '
      'normal rank to at least four, '
      'already treated in Sections 30–32. '
      'The remaining analysis can therefore '
      'assume exactly the three-coordinate '
      'full normal space.')
    p('<b>Proposition 50.1.</b> <i>The size pattern '
      '(5,1,1,1) has at least twenty '
      'facets.</i> Relabel so the large '
      'fibre is K₀. The other three '
      'cube corner vectors are linearly '
      'independent, so a linear shear '
      'makes their singleton heights '
      'zero. Write p₁,…,p₅ for the '
      'translated large-fibre vertices. '
      'In dual coordinates x₁,x₂,x₃,b '
      'the polar is precisely')
    eq('|xᵢ|≤1 (i=1,2,3),<br/>'
       '|x₁+x₂+x₃+⟨b,pₖ⟩|≤1 (k=1,…,5).','50.2')
    p('Put D={(s,b): |s+⟨b,pₖ⟩|≤1 for '
      'all k}. It is the polar of '
      'conv{±(1,pₖ)} in dimension three. '
      'That convex hull is full dimensional '
      'and has exactly ten vertices: '
      'the top and bottom polygons '
      'lie in the exposing planes '
      's=±1. A three-polytope with '
      'ten vertices has at least '
      'seven facets, from 2e≥3v '
      'and Euler. Thus D has at '
      'least seven vertices. It is '
      'compact, centrally symmetric and '
      'has the origin in its interior.')
    p('Equation (50.2) identifies P* with '
      'the fibre product of D and '
      'the cube B=[−1,1]³ over '
      's=x₁+x₂+x₃. We use two '
      'elementary vertex rules. A '
      'vertex y of D together with '
      'a vertex x of the corresponding '
      'cube section is a vertex of '
      'the fibre product: any nontrivial '
      'convex decomposition first fixes '
      'y, then fixes x. Conversely, '
      'a vertex x of B and a '
      'vertex y of its corresponding '
      'D section also give a vertex '
      'by the same argument in '
      'the reverse order.')
    p('If all vertices y=(s,b) of D have '
      '|s|&lt;3, each cube section '
      'x₁+x₂+x₃=s is a polygon '
      'with at least three vertices. '
      'The first rule gives at least '
      '3·7=21 different vertices of '
      'P*: different D vertices have '
      'different first coordinates in '
      'the product. In particular '
      'P has at least twenty facets.')
    p('Otherwise symmetry gives a point y∈D '
      'with s≥3. Convexity and an '
      'interior ball at zero show '
      'that the section s=1 has '
      'nonempty planar interior: scale '
      'y by 1/s&lt;1 and retain '
      'a scaled interior ball. Its '
      'compact polygon has at least '
      'three vertices. The section '
      's=3 is nonempty, by scaling '
      'y by 3/s≤1, and has '
      'at least one vertex. There '
      'are three cube vertices with '
      'coordinate sum one and one '
      'cube vertex with coordinate '
      'sum three. The second rule '
      'therefore supplies nine distinct '
      'vertices at height one and '
      'one at height three. Their '
      'negatives are ten further '
      'vertices, distinguished by '
      'negative height. Thus P* has '
      'at least twenty vertices in '
      'this case too. All boundary '
      'equalities, including maximum '
      'height exactly three, are '
      'included. □')
    p('This leaves four fibre-size patterns '
      'in the three-full-pair branch. '
      'The proposition is an all-real '
      'argument and uses no sample '
      'realizations or parameter rounding.')
