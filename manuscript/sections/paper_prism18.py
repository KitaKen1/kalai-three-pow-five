"""Real-coordinate edge count for a tetrahedral-prism facet and one extra pair."""

def add_prism18(p,eq,section,table,width):
    section(39,'A tetrahedral-prism facet at eighteen vertices')
    p('<b>Proposition 39.1.</b> <i>A centrally symmetric five-polytope '
      'with eighteen vertices and a facet combinatorially equivalent '
      'to Δ₁×Δ₃ has at least sixty-four edges.</i> '
      'Label the eight vertices of the facet F as x<sub>sk</sub>, '
      's∈{0,1}, k∈{0,1,2,3}. The remaining antipodal pair is ±z. '
      'Normalize its supporting form c by c(F)=1. Thus |c(z)|&lt;1. '
      'For a form c<sub>R</sub> supporting a ridge opposite row s, '
      'put h<sub>s</sub>=c−c<sub>R</sub>; similarly define '
      'g<sub>k</sub> for the ridge opposite column k. These forms '
      'are positive at their own row or column and zero at all '
      'others. The product recognition was proved in Section 16.')
    p('<b>A corner representation.</b> The map from six coefficients '
      'to forms, (α,β)↦Σα<sub>s</sub>h<sub>s</sub>+'
      'Σβ<sub>k</sub>g<sub>k</sub>, has a one-dimensional kernel. '
      'Indeed a kernel vector satisfies, at every vertex, '
      'α<sub>s</sub>h<sub>s</sub>(x<sub>sk</sub>)+'
      'β<sub>k</sub>g<sub>k</sub>(x<sub>sk</sub>)=0. '
      'If any α is zero all β and then all α are zero. '
      'Otherwise the α entries have the same sign and all β '
      'have the opposite sign. Fixing one α determines every '
      'β and the other α; the kernel therefore has dimension '
      'at most one. Six forms in five dimensions have a '
      'nonzero relation, so the kernel has dimension exactly '
      'one and the map is onto. Choose its vector (κ,λ) '
      'with κ<sub>s</sub>&gt;0 and λ<sub>k</sub>&lt;0.')
    p('Take any representation c=Σαh+Σβg. Since c(x<sub>sk</sub>)=1, '
      'the kernel relation implies '
      '−α<sub>s</sub>/κ<sub>s</sub>&lt;β<sub>k</sub>/(−λ<sub>k</sub>) '
      'for all s,k. Translate the coefficients along the '
      'kernel until the largest lower endpoint is attained. '
      'The resulting coefficients γ,δ satisfy γ≥0, '
      'γ<sub>0</sub>=0 after relabeling the rows, and δ&gt;0. '
      'For all sufficiently small τ&gt;0 both '
      'γ(τ)=γ+τκ and δ(τ)=δ+τλ are strictly positive.')
    eq('c=Σγ<sub>s</sub>(τ)h<sub>s</sub>+Σδ<sub>k</sub>(τ)g<sub>k</sub>,<br/>'
       'L<sub>τ</sub>(u,v)=Σu<sub>s</sub>γ<sub>s</sub>(τ)h<sub>s</sub>'
       '+Σv<sub>k</sub>δ<sub>k</sub>(τ)g<sub>k</sub>.','39.1')
    p('At x<sub>sk</sub>, L<sub>τ</sub> is a strictly positive '
      'convex combination of u<sub>s</sub> and v<sub>k</sub> '
      'when τ&gt;0. Put ξ=γ<sub>1</sub>h<sub>1</sub>(z), '
      'W<sub>k</sub>=δ<sub>k</sub>g<sub>k</sub>(z). Then '
      '|ξ+ΣW<sub>k</sub>|&lt;1. For ordered pairs '
      'a=(k,l), k≠l, set')
    eq('R(a)=Σ<sub>j≠k,l</sub>|W<sub>j</sub>|, &nbsp; '
       'ψ(a)=W<sub>k</sub>−W<sub>l</sub>−R(a).','39.2')
    p('<b>Candidate edges and blocked candidates.</b> There are '
      'twenty-four opposite-row candidates '
      '[x<sub>sk</sub>,−x<sub>1−s,l</sub>], k≠l. '
      'Choose u<sub>s</sub>=1,u<sub>1−s</sub>=−1, '
      'v<sub>k</sub>=1,v<sub>l</sub>=−1 and all other '
      'v entries in (−1,1). At τ&gt;0 only these '
      'two signed vertices have value one. At τ=0 '
      'the z-value ranges over the open interval '
      'W<sub>k</sub>−W<sub>l</sub>−ξ±R for s=0 '
      'and W<sub>k</sub>−W<sub>l</sub>+ξ±R for s=1; '
      'when R=0 the interval denotes its single value. '
      'If a value is strictly between −1 and 1, '
      'continuity gives an edge at sufficiently small τ&gt;0. '
      'Thus an actual nonedge has the whole interval '
      'above one or below minus one. Let U₀,U₁ '
      'be the actual nonedges of the first kind. Their '
      'antipodes are exactly the nonedges of the second kind, '
      'and hence there are at least 24−2(|U₀|+|U₁|) '
      'opposite-row edges. Moreover')
    eq('a∈U₀ ⇒ ψ(a)−ξ≥1, &nbsp; '
       'a∈U₁ ⇒ ψ(a)+ξ≥1.','39.3')
    p('If γ<sub>1</sub>&gt;0 there are also twelve '
      'same-row candidates [x<sub>0k</sub>,−x<sub>0l</sub>]. '
      'At τ=0 choose u₀=0,u₁∈(−1,1) and the same '
      'column signs. Only the two stated signed vertices '
      'are tight: the positive γ<sub>1</sub> makes '
      'the other row strict. The z-values range over '
      'W<sub>k</sub>−W<sub>l</sub>±(|ξ|+R). '
      'Writing U<sub>S</sub> for their upwards nonedges '
      'gives at least 12−2|U<sub>S</sub>| further edges and')
    eq('a∈U<sub>S</sub> ⇒ ψ(a)−|ξ|≥1.','39.4')
    p('Each upwards blocked candidate gives two edges '
      'incident with z, one to each of its endpoints. '
      'To see this explicitly, choose an admissible '
      'form L with only those two signed F vertices '
      'tight and with L(z)≥1. If L(z)&gt;1, '
      'L+a c, with a=(L(z)−1)/(1−c(z)), '
      'exposes z and the positive F endpoint; '
      'L−b c, with b=(L(z)−1)/(1+c(z)), '
      'exposes z and the negative F endpoint. '
      'All other vertices satisfy a strict inequality '
      'after normalization. If L(z)=1 the exposed '
      'face is the triangle of the two endpoints '
      'and z, whose sides are edges. Three distinct '
      'vertices cannot be collinear in a polytope. '
      'An interval with upper endpoint strictly '
      'greater than one permits such an L even '
      'when the candidate itself is an edge.')
    p('For opposite-row candidates use sufficiently '
      'small τ&gt;0 in this argument. If the '
      'interval merely touches one at τ=0 and '
      'the candidate is a nonedge, no small positive '
      'τ can move the whole interval into '
      '(−1,1); choosing a fixed interior set of '
      'parameters therefore still gives L(z)≥1. '
      'For same-row candidates τ=0 already has '
      'exactly the required tight endpoints.')
    p('Let d be the degree of z; always d≥5. '
      'Write H(V),T(V) for the sets of heads and '
      'tails of ordered pairs in V. The adjacency '
      'just proved gives, in the case γ<sub>1</sub>&gt;0,')
    eq('d≥|H(U₀∪U<sub>S</sub>)|+|H(U₁)|+'
       '|T(U₀)|+|T(U₁∪U<sub>S</sub>)|.','39.5')
    p('The four terms count positive row-zero, '
      'positive row-one, negative row-one and '
      'negative row-zero endpoints respectively. '
      'For the loose same-row set '
      'L<sub>S</sub>={a:W<sub>k</sub>−W<sub>l</sub>+|ξ|+R(a)&gt;1}, '
      'we also have')
    eq('d≥|H(U₀)|+|T(U₀)|+|T(U₀∩L<sub>S</sub>)|,<br/>'
       'd≥|H(U₁)|+|T(U₁)|+|H(U₁∩L<sub>S</sub>)|.','39.6')
    p('These inequalities count distinct signed row '
      'endpoints. They will compensate for missing '
      'candidate edges. The following elementary '
      'identity supplies the only compatibility rule:')
    eq('ψ(k,l)+ψ(k′,l′)≤0 '
       'if k≠k′ and l≠l′.','39.7')
    p('Indeed any positive occurrence of W<sub>k</sub> '
      'or W<sub>k′</sub> cancels a negative tail '
      'occurrence if it is the other tail; '
      'otherwise it is bounded by an absolute-value '
      'term in the other remainder. The same applies '
      'to negative tail occurrences. Every uncancelled '
      'term is therefore nonpositive. A set of '
      'ordered pairs that pairwise share a head or '
      'a tail lies in one row or one column: two '
      'distinct pairs sharing a head force every '
      'third compatible pair to share that head; '
      'the tail case is identical. Such a set has '
      'at most three elements.')
    p('<b>The parallel corner γ<sub>1</sub>=0.</b> Here ξ=0. '
      'Put U=|U₀|+|U₁|. The set Ψ={a:ψ(a)≥1} '
      'lies in a row or column by (39.7), so U≤6. '
      'We prove d≥U+4. If U≤1 this follows '
      'from d≥5. Otherwise take (k,l) in U₀∪U₁, '
      'and denote the other indices by i,j. '
      'The inequalities ψ(k,l)≥1 and |ΣW|&lt;1 '
      'give W<sub>k</sub>&gt;0,W<sub>l</sub>&lt;0. '
      'Put L={a:W<sub>head</sub>−W<sub>tail</sub>+R(a)&gt;1}. '
      'Every pair in L gives both row versions of '
      'the two z-adjacencies; hence '
      'd≥2(|H(L)|+|T(L)|).')
    p('If W<sub>j</sub>≠0, the pairs (k,i) and '
      '(i,l) are in L, since their upper values '
      'are at least ψ(k,l)+2|W<sub>j</sub>|. '
      'If W<sub>j</sub>&lt;0, (k,j) is also in L; '
      'if W<sub>j</sub>&gt;0, (j,l) is in L. '
      'Thus |H(L)|+|T(L)|≥5 and d≥10≥U+4. '
      'The same argument interchanges i,j if '
      'only W<sub>i</sub> is nonzero. If both '
      'are zero and W<sub>k</sub>−W<sub>l</sub>&gt;1, '
      'all four pairs (k,i),(k,j),(i,l),(j,l) '
      'are in L, giving d≥12.')
    p('The only remaining case has W<sub>i</sub>='
      'W<sub>j</sub>=0 and W<sub>k</sub>−W<sub>l</sub>=1. '
      'The signs above show that Ψ consists of '
      '(k,l) alone. Since U≥2 this pair would '
      'have to be in both U₀ and U₁. This tie '
      'is impossible. With the other column '
      'potentials zero, the derivatives of the '
      'two opposite-row z-values have sum '
      '2(W′<sub>k</sub>−W′<sub>l</sub>), where '
      'W′<sub>a</sub>=(λ<sub>a</sub>/δ<sub>a</sub>)W<sub>a</sub>. '
      'It is strictly negative because W<sub>k</sub>&gt;0, '
      'W<sub>l</sub>&lt;0 and λ&lt;0. At least one '
      'candidate consequently moves from z-value '
      'one to a value in (−1,1) for small '
      'τ&gt;0 and is an edge. Thus d≥U+4 '
      'in every parallel case.')
    p('<b>The other corner γ<sub>1</sub>&gt;0.</b> Put '
      'U=|U₀|+|U₁|+|U<sub>S</sub>|. We prove U≤d+2. '
      'This is immediate for U≤7. For U≥8 '
      'define the weak and strong sets '
      'Ψ₁={a:ψ(a)≥1−|ξ|} and '
      'Ψ₃={a:ψ(a)≥1+|ξ|}. Every strong pair '
      'is compatible with every weak pair by '
      '(39.7), since their ψ-sum is at least two. '
      'All three U sets are weak; U<sub>S</sub> '
      'and, according to the sign of ξ, '
      'either U₀ or U₁ are strong.')
    p('If Ψ₃ contains exactly one pair, there '
      'are at most five weak pairs compatible '
      'with it. Thus one U set has size at '
      'most five and each of the other two '
      'has size at most one, contradicting U≥8. '
      'If Ψ₃ contains two distinct pairs, '
      'they share a head or a tail and force '
      'every weak pair into the same row or '
      'column. Each U set then has size at '
      'most three. In a common row, U≥8 '
      'ensures U₁ and U₀∪U<sub>S</sub> are '
      'nonempty. Equation (39.5) gives '
      'd≥2+|U₀|+|U₁∪U<sub>S</sub>| '
      '≥U−1, because |U₁∩U<sub>S</sub>|≤3. '
      'In a common column the analogous '
      'calculation gives d≥U−1. Both are '
      'stronger than required.')
    p('It remains that Ψ₃ is empty. Then '
      'U<sub>S</sub> is empty; when ξ&lt;0 '
      'only U₀ can be nonempty, when ξ&gt;0 '
      'only U₁, and when ξ=0 neither. '
      'Consider U₀; the U₁ argument exchanges '
      'heads and tails. Let a=|H(U₀)| and '
      'b=|T(U₀)|. There are at most '
      'ab−max(0,a+b−4) distinct off-diagonal '
      'ordered pairs between these sets. For '
      '0≤a,b≤4 this is at most a+b+2 '
      'unless a=b=4. Hence (39.5) proves '
      '|U₀|≤d+2 unless a=b=4 and |U₀|≥11. '
      'For that last case at most one of '
      'the twelve ordered pairs is absent.')
    p('For any pair in U₀ outside L<sub>S</sub>, '
      '(39.3) and ξ&lt;0 give '
      'W<sub>k</sub>−W<sub>l</sub>+|ξ|−R≥1 '
      'while the loose upper value is at '
      'most one. Thus R=0. Suppose fewer '
      'than three tails occur in U₀∩L<sub>S</sub>. '
      'Choose two distinct omitted tails l,l′. '
      'At least two pairs in U₀ have each '
      'of these tails, since at most one '
      'ordered pair is absent. Their heads '
      'are distinct. Their two zero remainders '
      'force every W except possibly W<sub>l</sub> '
      'to vanish. The omitted tail l′ similarly '
      'forces every W except possibly W<sub>l′</sub> '
      'to vanish. Hence W=0. But a pair '
      'in U₀ would then imply |ξ|≥1, '
      'contrary to |ξ+ΣW|&lt;1. Therefore '
      '|T(U₀∩L<sub>S</sub>)|≥3. Equation '
      '(39.6) gives d≥4+4+3=11, '
      'and |U₀|≤12≤d+2. This completes '
      'the second corner as well.')
    p('<b>The edge count.</b> The two prism facets '
      'F and −F provide thirty-two edges. '
      'The candidate edges cross between these '
      'facets; none joins an antipodal pair. '
      'The edges incident with z or −z '
      'provide 2d distinct additional edges. '
      'All three collections are disjoint. '
      'In the parallel corner we obtain')
    eq('e≥32+24−2U+2d≥56+8=64.','39.8')
    p('In the other corner the same-row '
      'candidates add twelve more before '
      'the blocked pairs are removed, giving')
    eq('e≥32+24+12−2U+2d≥68−4=64.','39.9')
    p('The proof treats every real realization '
      'and the interval-endpoint ties explicitly; '
      'it does not assume generic coordinates.')
