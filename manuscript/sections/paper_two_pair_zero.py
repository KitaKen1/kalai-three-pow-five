"""All-real incidence closure of the zero-stress two-full-pair branch."""
def add_two_pair_zero(p,eq,section,table,width):
    section(44,'A saturated eight-vertex facet and the two-full-pair zero-stress case')
    p('<b>Lemma 44.1.</b> <i>For the row B=(8,19,19,8;38), '
      'the local weight q−3b+2η is at least six.</i> '
      'Section 41 already gives four, and η=3. '
      'Weight five would require q=2,b=1, '
      'contrary to η−q≠1. It suffices to '
      'exclude weight four. That equality '
      'forces q=b=1 and exactly one pentagonal '
      'two-face S: its contribution η−q=2 '
      'leaves no other long polygon. Denote '
      'the quadrilateral by Q. The two '
      'ridges A,B over Q are square pyramids. '
      'The two ridges C,D over S have six '
      'vertices and are pentagonal pyramids. '
      'Here A,B are ridge names; the row '
      'symbol B is used only in the lemma statement.')
    p('For completeness, the twelve ridge-count '
      'equations give four tetrahedra, two '
      'square pyramids and two ridges of '
      'triple (6,10,6). A seven-vertex ridge '
      'would put Q in that base, contradicting '
      'b=1. A prism reserves three quadrilaterals '
      'and is impossible. A (6,11,7) ridge '
      'has polygon excess one; it cannot '
      'contain S and would reserve a '
      'quadrilateral, again impossible. '
      'Substitute these zeros and two square '
      'pyramids in Σc=8, Σnc=38, Σfc=38 '
      'to obtain the stated counts. Thus '
      'A∩B=Q and C∩D=S; the other '
      'four ridges are tetrahedra.')
    p('The intersection of a square-pyramidal '
      'ridge with C or D has at most three '
      'vertices. Indeed, it is a proper face '
      'of a pentagonal pyramid. It cannot '
      'be the pentagonal base, since the '
      'square pyramid has only five vertices; '
      'every other polygonal face is a triangle. '
      'Consequently |A∩C|,|A∩D|,|B∩C|,|B∩D|≤3, '
      'where cardinalities count vertices.')
    p('An elementary four-set identity now supplies '
      'the missing geometric information. For '
      'each of the eight vertices v, let '
      'α(v)=1<sub>A</sub>(v)+1<sub>B</sub>(v) '
      'and β(v)=1<sub>C</sub>(v)+1<sub>D</sub>(v). '
      'Then (2−α)(2−β)+2α+2β=4+αβ. '
      'Summing and using |A|=|B|=5, '
      '|C|=|D|=6 gives')
    eq('Σ<sub>v</sub>(2−α(v))(2−β(v)) = '
       '|A∩C|+|A∩D|+|B∩C|+|B∩D|−12 ≤0.','44.1')
    p('Each summand is nonnegative, so all are '
      'zero. Every vertex is in A∩B or '
      'C∩D: Q∪S is the whole eight-vertex '
      'set. Since |Q|+|S|=9, their '
      'intersection is one vertex x. Write '
      'A=Q∪{a}, B=Q∪{b}, C=S∪{c}, '
      'D=S∪{d} at vertex-set level. '
      'Then a,b are distinct in S∖Q, '
      'and c,d are distinct in Q∖S.')
    p('The apex c belongs to at least six '
      'ridges of the four-dimensional facet: '
      'C itself and the five distinct '
      'other ridges meeting C in its five '
      'side triangles. Distinct side triangles '
      'give distinct partners because two '
      'ridges have a single intersection '
      'face. The same applies to d and D. '
      'With only eight ridges, at least '
      'four contain both c and d. Only '
      'A,B can contain Q, since a two-face '
      'has two ridge neighbours inside a '
      'four-polytope. Choose a common ridge '
      'T other than A,B. The proper face '
      'Q∩T contains c,d but is not Q; '
      'it is therefore the edge cd. '
      'Likewise Q∩C and Q∩D are the '
      'edges xc and xd. This gives a '
      'triangle of edges in the quadrilateral '
      'Q, impossible. The equality case '
      'is excluded and the lemma follows. □')
    p('<b>Proposition 44.2.</b> <i>The (16,18) endpoint '
      'with two full facet pairs and G=0 '
      'is excluded.</i> Section 42 gives S=10; '
      'all local g vanish, and their sum '
      'gives I=128. Four full facets contribute '
      '32 incidences. The fourteen remaining '
      'facets contribute 96 rather than '
      'their maximum 98. Antipodal parity '
      'therefore forces one six-vertex pair '
      'and six seven-vertex pairs. The '
      'Section 43 full-cover argument gives '
      'at least eight ridges per full '
      'facet. R₈≤36 and parity then '
      'give at most ten.')
    p('There are three six-vertex zero-g rows: '
      '(6,13,13,6;26), (6,14,15,7;29), '
      '(6,14,16,8;32). The nine seven-vertex '
      'rows are those of (43.1). The full '
      'row is (8,k,k+r−8,r;14+3r), with '
      '(k,r) in the eleven-element list '
      '(19,8),(19,9),(20,8),(20,9),(20,10), '
      '(21,8),(21,9),(21,10),(22,8),(22,9),(22,10). '
      'This is the Euler/excess arithmetic '
      'superset with the Section 36 fake '
      'rows removed; it assumes no catalogue '
      'of all eight-vertex four-polytopes.')
    p('Let s₀,s₁,s₂ count the six-vertex '
      'pairs, y,q,j,a,b,c,d,u,v the seven-vertex '
      'pairs, and f₀,…,f₁₀ the full pairs '
      'in the displayed orders. They sum '
      'to 1,6,2 respectively. Use the '
      'edge and ridge sums, 3e+122=Σ<sub>actual facets</sub>e(F), '
      'r=Σ<sub>pairs</sub>r(F), e+r≤118, '
      'even e,r, and the Section 41 bound '
      '9y+4q+4f₀+8f₁+3e≤210. '
      'Eliminating y with the count sum, '
      'five times the face bound plus '
      'seven times the weight bound yields')
    eq('39s₁+54s₂+4f₀+47f₁+15f₃+30f₄+24f₅+39f₆+54f₇<br/>'
       '+48f₈+63f₉+78f₁₀+4q+15a+30b+39c+54d+69u+84v≤24.','44.2')
    p('All coefficients are nonnegative. The '
      'remaining finite calculation consists '
      'only of three count compositions '
      'with sums 1,6,2 and the displayed '
      'integer equations. Its complete '
      'output is two profiles. Write '
      'D=(6,13,13,6;26), Hₖ=(8,k,k,8;38):')
    table([['<b>Actual facet multiset</b>','<b>(e,r)</b>'],
           ['D²Y⁴E⁸H₁₉⁴','(56,62)'],
           ['D²Y⁸J⁴H₂₀²H₂₁²','(58,60)']],[width*.75,width*.25])
    p('The independent count recurrence enumerates '
      'every nonnegative composition, with no '
      'geometric filtering. Alternatively, (44.2) '
      'sets every variable whose coefficient '
      'exceeds 24 to zero, bounds the '
      'remaining variables by 24 divided '
      'by their coefficients, and reduces '
      'the check to substitution in the '
      'three original sums. No unknown '
      'realization is deleted. The first '
      'profile saturates the weight-four '
      'lower bound on every H₁₉. Lemma '
      '44.1 excludes it.')
    p('In the second profile the weight budget '
      'is 72 and is attained. The H₂₀ '
      'facets have q=b=2 and four square '
      'pyramids, with two or three '
      'tetrahedral ridges by the twelve '
      'count equations. Every ridge of '
      'H₂₀ contains at most one quadrilateral. '
      'H₂₁ has q=b=1; D has no '
      'quadrilateral, and J has one. '
      'The prism base of a Y facet '
      'therefore has another Y facet '
      'as its unique partner. Saturation '
      'of the Section 35 link budget '
      'gives exactly two Y facets and '
      'one other facet over every '
      'quadrilateral, exactly as in Section 43.')
    p('Choose an H₂₀ facet H. Its two '
      'quadrilaterals give four distinct '
      'mixed quadrilaterals of the paired '
      'Y prisms, by the disjointness '
      'argument of Section 43. The third '
      'facet over a mixed quadrilateral '
      'cannot be H or −H. There is '
      'only one H₂₀ pair, so that third '
      'facet is D,J or H₂₁, each with '
      'at most one quadrilateral. The '
      'signed-vertex count of Section 43 '
      'still gives |H∩J′|=4: it uses '
      'only the two Y apices, the prism '
      'quad overlap and the absence of '
      'antipodal vertices in a facet. '
      'Its four-vertex intersection cannot '
      'be a quadrilateral, since J′ '
      'already has its distinct mixed '
      'quadrilateral; it is a tetrahedral '
      'ridge. Distinct mixed quadrilaterals '
      'have distinct third facets and '
      'distinct ridge intersections with H. '
      'Thus H would have at least four '
      'tetrahedral ridges, exceeding three. '
      'The second profile is impossible as well. □')
