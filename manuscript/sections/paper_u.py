"""All-real geometric exclusion of the nine-vertex U facet at at most eighteen facets."""

def add_u(p,eq,section,table,width):
    from .paper_endpoints import tuple_text
    from verification.verify_mathematics import U_TABLE
    section(38,'The nine-vertex U facet forces at least twenty facets')
    p('<b>Proposition 38.1.</b> <i>If v(P)=18 and P contains '
      'a facet of row U=(9,19,17,7;38), then h(P)≥20.</i> '
      'Its polar as a four-polytope has row (7,17,19,9;38). '
      'The small Gale catalogue gives exactly ten sorted '
      'codes with that row. The following permutations '
      'carry all their facet masks to '
      '15,23,27,29,46,86,102,122,124.')
    table([['<b>Signed Gale code</b>','<b>Permutation i ↦ π(i)</b>']]+
          [[tuple_text(cs),tuple_text(pi)] for cs,pi in U_TABLE.items()],
          [width/2,width/2])
    p('The face criterion of Section 7 checks each mask '
      'directly. Completeness follows by exhausting all '
      'seven-point sorted codes in that criterion. '
      'Dualizing gives nine vertices x₀,…,x₈ of U; '
      'the bits of the ith mask specify which of '
      'its seven three-faces G₀,…,G₆ contain xᵢ. '
      'Since U is full, P=conv{±x₀,…,±x₈}. In '
      'particular G₃ and G₄ are triangular prisms '
      'with product edges')
    eq('A=[x₂,x₇], B=[x₃,x₈], C=[x₀,x₄], D=[x₁,x₅].','38.1')
    p('The pairs AB,AC,BC,AD,BD lie respectively in '
      'quadrilateral planes with vertex sets '
      '{2,3,7,8}, {0,2,4,7}, {0,3,4,8}, '
      '{1,2,5,7}, {1,3,5,8}. The C,D endpoints '
      'and z=x₆ lie in the pentagon '
      '{0,1,4,5,6}=G₁∩G₂. Thus the four '
      'supporting lines in (38.1) are all '
      'parallel or concurrent. Here is the '
      'linear-algebra proof, to include every '
      'real realization. If A,B have independent '
      'directions, their common plane makes '
      'them meet at p. If C did not pass through '
      'p, the planes containing A,C and B,C '
      'would both equal the plane spanned by '
      'C and p; G₃ would then be planar, '
      'contradicting its dimension three. '
      'Hence C passes through p, and the '
      'same argument in G₄ applies to D. '
      'If A,B are parallel, a direction '
      'of C independent of theirs would '
      'make those same two planes equal '
      'and again collapse G₃ to dimension '
      'two. Thus C and similarly D are '
      'parallel to them.')
    p('<b>Parallel case.</b> Put d=x₇−x₂. Write '
      'x₈=x₃+μ<sub>B</sub>d, x₄=x₀+μ<sub>C</sub>d '
      'and x₅=x₁+μ<sub>D</sub>d, with all μ nonzero. '
      'The pentagon plane gives '
      'z=x₀+αd+β(x₁−x₀). A functional zero '
      'on G₃ and strictly positive at the '
      'remaining U vertices gives β&gt;0; '
      'the analogous functional for G₄ '
      'gives β&lt;1. The five vectors '
      'x₂,x₃,x₀,x₁,d form a basis: '
      'their span contains all nine xᵢ '
      'by these formulas, hence is ℝ⁵.')
    p('For every (a,b,c,e)∈{−1,1}⁴ define '
      'the functional y with values a,b,c,e '
      'on x₂,x₃,x₀,x₁ and value zero '
      'on d. All |y(xᵢ)|≤1, since '
      'y(z)=(1−β)c+βe. At least five '
      'independent constraints are tight: '
      'the constraints on x₂,x₇ determine '
      'd, and those on x₃,x₀,x₁ determine '
      'the other basis directions. Thus '
      'these are sixteen distinct vertices '
      'of P*. Those with y(z)=1 '
      'necessarily have c=e=1, and '
      'annihilate both d and x₀−x₁.')
    p('The facet of P* exposed by the vertex '
      'z is four-dimensional and its vertices '
      'span ℝ⁵ linearly, since its affine '
      'hyperplane has value one at z. The '
      'sixteen vertices just constructed '
      'that belong to this facet annihilate '
      'the two-dimensional space '
      'span{d,x₀−x₁}. At most one further '
      'vertex in that facet cannot remove '
      'this common kernel: there remains '
      'a nonzero vector annihilated by '
      'all its vertices. Therefore there '
      'are at least two further vertices '
      'tight at z. Their negatives are '
      'distinct further vertices, none '
      'among the original sixteen. This '
      'gives at least twenty vertices '
      'of P*, as required.')
    p('<b>Concurrent case.</b> Write the endpoints '
      'on the four lines as p+uᵢ and p+τᵢuᵢ '
      '(i=A,B,C,D). A supporting form of '
      'G₂ is zero on line B and positive '
      'on both A endpoints, so τ<sub>A</sub>&gt;0. '
      'Use G₁ for B, G₄ for C and G₃ '
      'for D to get τᵢ&gt;0 for all i. '
      'Distinct endpoints give τᵢ≠1. '
      'The pentagon plane gives '
      'z=p+w<sub>C</sub>u<sub>C</sub>+'
      'w<sub>D</sub>u<sub>D</sub>; the '
      'positive supporting forms of G₄ '
      'and G₃ give w<sub>C</sub>,w<sub>D</sub>&gt;0. '
      'Again p,u<sub>A</sub>,u<sub>B</sub>, '
      'u<sub>C</sub>,u<sub>D</sub> is a '
      'basis because it spans all vertices.')
    eq('mᵢ=max(1,τᵢ),  M<sub>C</sub>=max(1,τ<sub>C</sub>,w<sub>C</sub>),<br/>'
       'M<sub>D</sub>=max(1,τ<sub>D</sub>,w<sub>D</sub>).','38.2')
    p('Construct twelve functionals y by '
      'y(p)=1; independently choose '
      'y(u<sub>A</sub>)∈{0,−2/m<sub>A</sub>} '
      'and y(u<sub>B</sub>)∈{0,−2/m<sub>B</sub>}; '
      'choose the pair of C,D values from '
      '(0,0), (−2/M<sub>C</sub>,0), '
      '(0,−2/M<sub>D</sub>). Every endpoint '
      'and z then has value in [−1,1], '
      'since 0&lt;t≤M implies '
      '−1≤1−2t/M≤1. Thus y∈P*. '
      'We verify that each is a vertex, '
      'including ties among the maxima.')
    p('Let a linear perturbation vanish on '
      'all tight constraints. At least '
      'one of C,D is unlowered; its '
      'two endpoints have value one '
      'and their equations force the '
      'perturbation to vanish on p '
      'and on that line’s u, because '
      'τ≠1. If the other is lowered, '
      'a maximum among 1,τ,w is '
      'attained. The corresponding '
      'endpoint or z has value −1 '
      'and forces its u component '
      'to vanish as well. For A '
      'and B an unlowered pair gives '
      'both equations; a lowered '
      'line has an endpoint attaining '
      'm and value −1. With the p '
      'component already zero, each '
      'forces its u component zero. '
      'The perturbation therefore '
      'vanishes on the basis. This '
      'proves extremality without '
      'assuming unique maxima or '
      'generic coordinates.')
    p('The twelve functionals are distinct '
      'by their basis values, all have '
      'value one at p, and their '
      'negatives have value −1 there. '
      'Hence P* has at least twenty-four '
      'vertices in the concurrent '
      'case. Both cases prove h(P)≥20 '
      'and Proposition 38.1. In '
      'particular U is absent on both '
      'sides at (18,18), and on the '
      'polar side at (16,18).')
